# ============ 模仿示例：温室温度报警 ============
# if 后面跟一个「判断」，成立就执行缩进（4 个空格）里的代码。
# 不成立就跳到 elif / else 继续判断。
wen_du = 32

if wen_du > 35:
    print("温度过高！打开通风")
elif wen_du > 30:
    print("温度偏高，注意观察")
elif wen_du >= 20:
    print("温度正常")
else:
    print("温度偏低，打开加热")

# 逻辑运算符：and（两边都成立才成立）、or（一边成立就成立）
shi_du = 60
if wen_du > 35 and shi_du > 70:
    print("高温高湿，危险！")

